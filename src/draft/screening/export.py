"""Hand a screened concept to Draft's generator.

Writes a parameter-override YAML for ``src/draft/robots/humanoid`` so that

    python scripts/generate_robot.py --robot humanoid --overrides <file>

compiles the screened proportions and actuators into an MJCF (needs MuJoCo).
One motor class per actuator slot, anchored on the catalogue part when the
concept picked one. Draft has no parallel mechanisms: a parallel ankle is
exported as two serial joints, each with the ankle-drive actuator.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .sizing import ConceptResult

#: screening slot -> (Draft motor-class token, Draft joint roles it drives)
CLASS_OF = {
    "hip_pitch": ("HP", ["hip_pitch"]),
    "hip_roll": ("HR", ["hip_roll"]),
    "hip_yaw": ("HY", ["hip_yaw"]),
    "knee": ("KN", ["knee"]),
    "ankle_pitch": ("AP", ["ankle_pitch"]),
    "ankle_roll": ("AR", ["ankle_roll"]),
    "ankle_drive": ("AD", ["ankle_pitch", "ankle_roll"]),
    "waist_yaw": ("WY", ["torso_yaw"]),
    "waist_roll": ("WR", ["torso_roll"]),
    "waist_pitch": ("WP", ["torso_pitch"]),
    "shoulder_pitch": ("SP", ["shoulder_pitch"]),
    "shoulder_roll": ("SR", ["shoulder_roll"]),
    "shoulder_yaw": ("SY", ["shoulder_yaw"]),
    "elbow": ("EL", ["elbow"]),
    "wrist_yaw": ("WYW", ["wrist_yaw"]),
    "wrist_pitch": ("WPT", ["wrist_pitch"]),
    "wrist_roll": ("WRL", ["wrist_roll"]),
}

_FRICTION = [(60.0, 0.1, 0.01), (20.0, 0.08, 0.008), (0.0, 0.05, 0.005)]


def draft_overrides(res: ConceptResult) -> dict:
    g = res.concept.geo
    r = lambda x: round(float(x), 4)   # noqa: E731
    head_r = 0.06 * g.height
    p: dict = {
        # legs: Draft's thigh is lower_hip_link + upper_leg_link (hip pitch -> knee)
        "lower_hip_link_length": r(0.43 * g.thigh),
        "upper_leg_link_length": r(0.57 * g.thigh),
        "lower_leg_link_length": r(g.shank),
        "foot_h": f"${{max({r(g.ankle_h)} - ankle_link_length, foot_plate_h + 0.01)}}",
        "foot_length": r(g.foot_length),
        "foot_width": r(g.foot_width),
        "foot_offset_x": r(0.5 * g.foot_length - g.heel),
        "hip_width": r(g.hip_width),
        # trunk: shoulder axis above the hip-pitch axis
        "torso_length": f"${{{r(g.hip_to_shoulder)} - torso_roll_motor_r}}",
        "shoulder_width": f"${{max({r(g.shoulder_width)} - 0.4 * shoulder_pitch_motor_L, 0.1)}}",
        "head_radius": r(head_r),
        "neck_length": r(max(g.head_neck - head_r, 0.05)),
        # arms
        "bicep_link_length": f"${{max({r(g.upper_arm)} - lower_shoulder_link_length, 0.03)}}",
        "forearm_link_length": r(g.forearm),
        "hand_link_length": f"${{max({r(g.hand)} - upper_wrist_link_length - lower_wrist_link_length, 0.03)}}",
    }
    hypothetical = False
    for slot, act in res.chosen.items():
        cls, roles = CLASS_OF[slot]
        p[f"{cls}_motor_effort"] = r(act.tau_peak)
        p[f"{cls}_motor_velocity"] = r(act.omega_nl)
        if act.gear:
            p[f"{cls}_motor_gear"] = r(act.gear)
        for lim, fr, dmp in _FRICTION:
            if act.tau_peak >= lim:
                p[f"{cls}_motor_friction"], p[f"{cls}_motor_damping"] = fr, dmp
                break
        if act.source == "catalog" and act.vendor != "custom":
            p[f"_{cls}_motor_catalog"] = act.name
        if not act.feasible:
            hypothetical = True
        for role in roles:
            p[f"{role}_mot"] = cls
    # roles this concept does not have: keep the link, drop the joint
    present = {role for s in res.chosen for role in CLASS_OF[s][1]}
    fallback = {"torso_roll": "WY", "torso_pitch": "WY", "torso_yaw": "WY",
                "wrist_yaw": "EL", "wrist_pitch": "EL", "wrist_roll": "EL"}
    for role, cls in fallback.items():
        if role not in present:
            if f"{cls}_motor_effort" not in p:
                cls = "EL"
            p[f"{role}_mot"] = cls
            p[f"{role}_dof"] = False
    if hypothetical:
        p["allow_hypothetical"] = True
    return p


def write_draft_overrides(res: ConceptResult, path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    head = [
        f"# Draft overrides for concept '{res.spec['name']}' (generated by the screening).",
        "#   python scripts/generate_robot.py --robot humanoid --overrides " + path.name,
        "# Proportions and one motor class per actuator slot. Draft re-derives every",
        "# mass from its own trends and runs its feasibility gate, so its numbers will",
        "# differ a little from the screening's planar model.",
    ]
    if res.spec["mechanism"]["ankle"] == "parallel":
        head.append("# Parallel ankle exported as two serial joints sharing the ankle-drive class.")
    body = yaml.safe_dump(draft_overrides(res), sort_keys=False, allow_unicode=True)
    path.write_text("\n".join(head) + "\n" + body, encoding="utf-8")
    return path
